// Every scene is data, not a component. The engine blends between these token
// sets, so adding a new sky is just adding an entry here.
//
// Positions (sunX, sunY, moonX, moonY) are in landscape viewBox units
// (1600 × 900, looking north: west is on the left, east on the right).

export const COLOR_KEYS = [
  'skyZenith',
  'skyMid',
  'skyHorizon',
  'sun',
  'glow',
  'hillFar',
  'hillNear',
  'canopy',
  'mosqueShade',
  'mosqueLit',
  'facade',
  'mist',
  'ink',
  'cloudLit',
  'cloudShadow',
] as const

export const NUM_KEYS = [
  'skyMidStop', // 0..1, where the mid colour sits between zenith and horizon
  'sunX',
  'sunY',
  'sunSize',
  'sunAlpha',
  'glowStrength',
  'moonX',
  'moonY',
  'moonAlpha',
  'stars',
  'lightDir', // -1 lit from the west (left), +1 lit from the east (right)
  'mosqueLights',
  'mistAmount',
  'cloudCover', // 0..1 share of sky covered
  'cloudOpacity',
  'cloudSpeed', // drift multiplier
  'cloudScale', // >1 smaller, more broken clouds; <1 big masses
  'rain',
  'lightning', // chance of occasional sheet lightning
  'rimLight', // low-sun rim on the tree canopy
  'wetSheen', // gloss on wet marble
  'rainbow',
  'hillLights', // Daman-e-Koh, Monal road, Saidpur, city street lights
  'birds',
] as const

export type ColorKey = (typeof COLOR_KEYS)[number]
export type NumKey = (typeof NUM_KEYS)[number]

export type SceneDef = {
  id: SceneId
  name: string
  time: string
  colors: Record<ColorKey, string>
  nums: Record<NumKey, number>
}

